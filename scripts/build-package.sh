#!/usr/bin/env bash
# OmaStack Package & Installer Builder for Omarchy Linux
# Builds:
#  1. Native Arch Linux package: dist/omastack-1.0.0-1-any.pkg.tar.zst
#  2. Self-extracting offline installer: dist/omastack-installer.run
#  3. Standalone offline distribution tarball: dist/omastack-1.0.0-linux.tar.gz
# SPDX-License-Identifier: MIT

set -euo pipefail

ROOT_DIR=""
if [ -f "$(pwd)/install.sh" ]; then
    ROOT_DIR="$(pwd)"
elif [ -f "$(dirname "${BASH_SOURCE[0]}")/install.sh" ]; then
    ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
elif [ -f "$(dirname "${BASH_SOURCE[0]}")/../install.sh" ]; then
    ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
else
    ROOT_DIR="$(pwd)"
fi
cd "${ROOT_DIR}"
SCRIPT_DIR="${ROOT_DIR}"

BOLD="\033[1m"
GREEN="\033[32m"
CYAN="\033[36m"
YELLOW="\033[33m"
RED="\033[31m"
RESET="\033[0m"

PKGNAME="omastack"
PKGVER="1.0.0"
PKGREL="1"
ARCH="any"
FULL_PKG_NAME="${PKGNAME}-${PKGVER}-${PKGREL}-${ARCH}.pkg.tar.zst"

echo -e "${CYAN}${BOLD}"
echo "=================================================================="
echo "⚡ OmaStack Packaging Suite for Omarchy Linux (v${PKGVER}-${PKGREL})"
echo "=================================================================="
echo -e "${RESET}"

# Step 1: Run complete test suite before packaging
echo -e "${BOLD}Step 1: Running validation test suite...${RESET}"
bash "${SCRIPT_DIR}/install.sh" --test

# Step 2: Prepare clean dist directory
echo -e "\n${BOLD}Step 2: Preparing build staging environment...${RESET}"
DIST_DIR="${SCRIPT_DIR}/dist"
STAGE_DIR="${DIST_DIR}/staging_pkg"
TMP_BUILD="${DIST_DIR}/tmp_build"

rm -rf "${DIST_DIR}"
mkdir -p "${DIST_DIR}" "${STAGE_DIR}" "${TMP_BUILD}"

# Step 3: Build Arch Linux package (omastack-1.0.0-1-any.pkg.tar.zst)
echo -e "\n${BOLD}Step 3: Building native Arch Linux package (.pkg.tar.zst)...${RESET}"

# Install using install.sh with DESTDIR and /usr prefix
bash "${SCRIPT_DIR}/install.sh" --destdir "${STAGE_DIR}" --prefix "/usr"

# Extra doc and license files
mkdir -p "${STAGE_DIR}/usr/share/licenses/${PKGNAME}" "${STAGE_DIR}/usr/share/doc/${PKGNAME}"
cp "${SCRIPT_DIR}/LICENSE" "${STAGE_DIR}/usr/share/licenses/${PKGNAME}/"
if [ -f "${SCRIPT_DIR}/README.md" ]; then
    cp "${SCRIPT_DIR}/README.md" "${STAGE_DIR}/usr/share/doc/${PKGNAME}/"
fi

# Calculate installed package size in bytes
INSTALLED_SIZE=$(du -sb "${STAGE_DIR}" 2>/dev/null | awk '{print $1}' || du -sk "${STAGE_DIR}" | awk '{print $1 * 1024}')
BUILD_DATE=$(date +%s)

# Generate .PKGINFO
cat << EOF > "${STAGE_DIR}/.PKGINFO"
# Generated by OmaStack package builder
# $(date -u)
pkgname = ${PKGNAME}
pkgbase = ${PKGNAME}
pkgver = ${PKGVER}-${PKGREL}
pkgdesc = Native, zero-bloat ephemeral full-stack sandbox launcher and Docker manager for Omarchy Linux
url = https://github.com/anax/omastack
builddate = ${BUILD_DATE}
packager = Anas Mohamed <nxmohamed@gmail.com>
size = ${INSTALLED_SIZE}
arch = ${ARCH}
license = MIT
depend = bash
depend = docker
depend = docker-compose
depend = iproute2
depend = wl-clipboard
optdepend = caddy: Local *.oma.local reverse proxy support
optdepend = mkcert: Automated trusted local SSL certificate generation
optdepend = rofi: Interactive application launcher menu
optdepend = walker: Fast application launcher runner
optdepend = waybar: Status bar module integration
optdepend = libnotify: Desktop notification alerts
EOF

# Copy .INSTALL script
cp "${SCRIPT_DIR}/omastack.install" "${STAGE_DIR}/.INSTALL"

# Pack using bsdtar and zstd compression
(
    cd "${STAGE_DIR}"
    bsdtar -cf - .PKGINFO .INSTALL usr | zstd -c -T0 -19 > "${DIST_DIR}/${FULL_PKG_NAME}"
)
echo -e "  ${GREEN}✔ Built:${RESET} dist/${FULL_PKG_NAME} ($(du -h "${DIST_DIR}/${FULL_PKG_NAME}" | awk '{print $1}'))"

# Step 4: Build Self-Extracting Executable Installer (.run)
echo -e "\n${BOLD}Step 4: Building self-extracting offline installer (.run)...${RESET}"

PAYLOAD_DIR="${TMP_BUILD}/omastack-${PKGVER}"
mkdir -p "${PAYLOAD_DIR}" "${PAYLOAD_DIR}/omastack"

# Copy all necessary files into payload directory
cp "${SCRIPT_DIR}/install.sh" "${PAYLOAD_DIR}/"
cp "${SCRIPT_DIR}/LICENSE" "${PAYLOAD_DIR}/"
cp "${SCRIPT_DIR}/README.md" "${PAYLOAD_DIR}/"
cp "${SCRIPT_DIR}/manifest.json" "${PAYLOAD_DIR}/"
cp "${SCRIPT_DIR}/BarWidget.qml" "${PAYLOAD_DIR}/"
cp "${SCRIPT_DIR}/Panel.qml" "${PAYLOAD_DIR}/"
cp "${SCRIPT_DIR}/omastack-icon.svg" "${PAYLOAD_DIR}/"
cp "${SCRIPT_DIR}/metadata.json" "${PAYLOAD_DIR}/" 2>/dev/null || true

# Copy omastack application directory
cp -r "${SCRIPT_DIR}/omastack/bin" "${PAYLOAD_DIR}/omastack/"
cp -r "${SCRIPT_DIR}/omastack/lib" "${PAYLOAD_DIR}/omastack/"
cp -r "${SCRIPT_DIR}/omastack/templates" "${PAYLOAD_DIR}/omastack/"
if [ -d "${SCRIPT_DIR}/omastack/assets" ]; then
    cp -r "${SCRIPT_DIR}/omastack/assets" "${PAYLOAD_DIR}/omastack/"
fi
if [ -f "${SCRIPT_DIR}/omastack/omastore.toml" ]; then
    cp "${SCRIPT_DIR}/omastack/omastore.toml" "${PAYLOAD_DIR}/omastack/"
fi
cp "${SCRIPT_DIR}/manifest.json" "${PAYLOAD_DIR}/omastack/"
cp "${SCRIPT_DIR}/BarWidget.qml" "${PAYLOAD_DIR}/omastack/"
cp "${SCRIPT_DIR}/Panel.qml" "${PAYLOAD_DIR}/omastack/"
cp "${SCRIPT_DIR}/omastack-icon.svg" "${PAYLOAD_DIR}/omastack/"
cp "${SCRIPT_DIR}/LICENSE" "${PAYLOAD_DIR}/omastack/"

# Create compressed tarball payload
(
    cd "${TMP_BUILD}"
    tar -czf "payload.tar.gz" -C "omastack-${PKGVER}" .
)

RUN_INSTALLER="${DIST_DIR}/omastack-installer.run"

cat << 'HEADER_EOF' > "${RUN_INSTALLER}"
#!/usr/bin/env bash
# OmaStack Self-Extracting Offline Installer for Omarchy Linux
# Native, zero-bloat ephemeral full-stack sandbox launcher
# SPDX-License-Identifier: MIT

set -euo pipefail

BOLD="\033[1m"
GREEN="\033[32m"
CYAN="\033[36m"
YELLOW="\033[33m"
RED="\033[31m"
RESET="\033[0m"

echo -e "${CYAN}${BOLD}"
echo "  ___   __  __    _    ____ _____  _    ____ _  __"
echo " / _ \ |  \/  |  / \  / ___|_   _|/ \  / ___| |/ /"
echo "| | | || |\/| | / _ \ \___ \ | | / _ \| |   | ' / "
echo "| |_| || |  | |/ ___ \ ___) || |/ ___ \ |___| . \ "
echo " \___/ |_|  |_/_/   \_\____/ |_/_/   \_\____|_|\_\\"
echo -e "${RESET}"
echo -e "${CYAN}⚡ OmaStack Self-Extracting Installer for Omarchy Linux${RESET}\n"

TMP_EXTRACT=$(mktemp -d -t omastack-pkg-XXXXXX)
cleanup() {
    rm -rf "${TMP_EXTRACT}"
}
trap cleanup EXIT INT TERM

echo -e "➜ Extracting embedded OmaStack payload..."
PAYLOAD_LINE=$(grep -a -n "^__OMASTACK_PAYLOAD_BEGINS__" "$0" | cut -d: -f1)
tail -n +$((PAYLOAD_LINE + 1)) "$0" | tar -xz -C "${TMP_EXTRACT}"

if [ ! -f "${TMP_EXTRACT}/install.sh" ]; then
    echo -e "${RED}✖ Failed to extract installer payload.${RESET}" >&2
    exit 1
fi

chmod +x "${TMP_EXTRACT}/install.sh" "${TMP_EXTRACT}/omastack/bin/"* 2>/dev/null || true

# Forward all arguments directly to install.sh
"${TMP_EXTRACT}/install.sh" "$@"
exit 0
__OMASTACK_PAYLOAD_BEGINS__
HEADER_EOF

cat "${TMP_BUILD}/payload.tar.gz" >> "${RUN_INSTALLER}"
chmod +x "${RUN_INSTALLER}"

# Create convenience alias for release
cp "${RUN_INSTALLER}" "${DIST_DIR}/omastack-${PKGVER}-linux-x86_64.run"

echo -e "  ${GREEN}✔ Built:${RESET} dist/omastack-installer.run ($(du -h "${RUN_INSTALLER}" | awk '{print $1}'))"
echo -e "  ${GREEN}✔ Built:${RESET} dist/omastack-${PKGVER}-linux-x86_64.run"

# Step 5: Build Standalone Offline Distribution Tarball (.tar.gz)
echo -e "\n${BOLD}Step 5: Building standalone offline distribution tarball (.tar.gz)...${RESET}"
TARBALL_NAME="omastack-${PKGVER}-linux.tar.gz"
(
    cd "${TMP_BUILD}"
    tar -czf "${DIST_DIR}/${TARBALL_NAME}" "omastack-${PKGVER}"
)
echo -e "  ${GREEN}✔ Built:${RESET} dist/${TARBALL_NAME} ($(du -h "${DIST_DIR}/${TARBALL_NAME}" | awk '{print $1}'))"

# Step 6: Generate SHA256 Checksums
echo -e "\n${BOLD}Step 6: Generating SHA256 checksums...${RESET}"
(
    cd "${DIST_DIR}"
    rm -f SHA256SUMS *.sha256
    for f in *.pkg.tar.zst *.run *.tar.gz; do
        if [ -f "${f}" ]; then
            shasum -a 256 "${f}" > "${f}.sha256"
            shasum -a 256 "${f}" >> SHA256SUMS
        fi
    done
)
echo -e "  ${GREEN}✔ Generated:${RESET} dist/SHA256SUMS"

# Clean up temp build staging
rm -rf "${STAGE_DIR}" "${TMP_BUILD}"

echo -e "\n${GREEN}${BOLD}==================================================================${RESET}"
echo -e "${GREEN}${BOLD}✔ OMASTACK INSTALLABLE PACKAGES BUILT SUCCESSFULLY!${RESET}"
echo -e "${GREEN}${BOLD}==================================================================${RESET}\n"

ls -lh "${DIST_DIR}"
echo ""
